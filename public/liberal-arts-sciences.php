	<script>
		document.addEventListener("DOMContentLoaded",function(){
			if(window.lucide){
				lucide.createIcons();
			}
			const modal=document.getElementById("programModal");
			const modalTitle=document.getElementById("programModalTitle");
			const modalVision=document.getElementById("programModalVision");
			const modalMission=document.getElementById("programModalMission");
			const modalNumber=document.getElementById("programModalNumber");
			const programLinks=document.querySelectorAll(".program-read-more");
			const closeButtons=document.querySelectorAll("[data-modal-close]");
			const filterButtons=document.querySelectorAll(".cba-filters button");
			const programCards=document.querySelectorAll(".cba-program-card");
			const vision="CLAS serves the student through undergraduate programs founded in the pursuit of higher education with academic freedom and social awareness, services and justice.";
			const mission="To provide quality and relevant instruction in core courses to all undergraduate programs of the University, the CLAS aims to accomplish its mission through continuous improvement of teaching, services, research, course offerings, program content, and relationships with the community, alumni, private and public sectors.";
			const programDescriptions={
				"political-science":{title:"AB Political Science",vision:vision,mission:mission},
				"communication":{title:"BA Communication",vision:vision,mission:mission},
				"public-administration":{title:"Bachelor of Public Administration",vision:vision,mission:mission},
				"public-administration-special":{title:"Bachelor of Public Administration (Special Program)",vision:vision,mission:mission},
				"computer-science":{title:"Bachelor of Science in Computer Science",vision:vision,mission:mission},
				"entertainment-multimedia":{title:"Bachelor of Science in Entertainment and Multimedia Computing",vision:vision,mission:mission},
				"information-system":{title:"Bachelor of Science in Information System",vision:vision,mission:mission},
				"information-technology":{title:"Bachelor of Science in Information Technology",vision:vision,mission:mission},
				"mathematics":{title:"Bachelor of Science in Mathematics",vision:vision,mission:mission},
				"psychology":{title:"Bachelor of Science in Psychology",vision:vision,mission:mission}
			};
			function openProgramModal(card){
				const data=programDescriptions[card.dataset.program];
				const number=card.querySelector(".cba-program-number");
				if(!data){
					return;
				}
				modalTitle.textContent=data.title;
				modalVision.textContent=data.vision;
				modalMission.textContent=data.mission;
				modalNumber.textContent=number ? number.textContent.trim() : "";
				modal.classList.add("show");
				modal.setAttribute("aria-hidden","false");
				document.body.classList.add("program-modal-open");
			}
			function closeProgramModal(){
				modal.classList.remove("show");
				modal.setAttribute("aria-hidden","true");
				document.body.classList.remove("program-modal-open");
			}
			programLinks.forEach(function(link){
				link.addEventListener("click",function(event){
					event.preventDefault();
					const card=link.closest(".cba-program-card");
					if(card){
						openProgramModal(card);
					}
				});
			});
			closeButtons.forEach(function(button){
				button.addEventListener("click",closeProgramModal);
			});
			filterButtons.forEach(function(button){
				button.addEventListener("click",function(){
					const filter=button.dataset.filter;
					filterButtons.forEach(function(item){
						item.classList.toggle("active",item===button);
					});
					programCards.forEach(function(card){
						const program=card.dataset.program;
						const matches=filter==="all"||program===filter||(filter==="public-administration"&&program==="public-administration-special");
						card.hidden=!matches;
					});
				});
			});
			document.addEventListener("keydown",function(event){
				if(event.key==="Escape"&&modal.classList.contains("show")){
					closeProgramModal();
				}
			});
		});
	</script>
